export const CUSTOMER_LIST = CUSTOMER_DATABASE;

const STORAGE_KEY = "trcn_custom_customers";

/**
 * Gets all customers (preloaded + localStorage custom/imported)
 */
export function getAllCustomers(): CustomerRecord[] {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored) {
      const parsedStored: CustomerRecord[] = JSON.parse(stored);
      if (Array.isArray(parsedStored) && parsedStored.length > 0) {
        const codeMap = new Map<string, CustomerRecord>();
        CUSTOMER_DATABASE.forEach((c) => codeMap.set(c.code.toUpperCase(), c));
        parsedStored.forEach((c) => codeMap.set(c.code.toUpperCase(), c));
        return Array.from(codeMap.values());
      }
    }
  } catch (e) {
    console.error("Error loading custom customers:", e);
  }
  return CUSTOMER_DATABASE;
}

/**
 * Generates the next sequential customer member code (e.g. TRCN-457)
 */
export function getNextCustomerCode(): string {
  const all = getAllCustomers();
  let maxNum = 456;

  all.forEach((c) => {
    const match = c.code.match(/TRCN-(\d+)/i);
    if (match && match[1]) {
      const n = parseInt(match[1], 10);
      if (!isNaN(n) && n > maxNum) {
        maxNum = n;
      }
    }
  });

  const nextNum = maxNum + 1;
  const padded = nextNum < 100 ? String(nextNum).padStart(3, "0") : String(nextNum);
  return `TRCN-${padded}`;
}

/**
 * Adds a new registered customer to the database & localStorage
 */
export function addCustomerRecord(newCustomer: CustomerRecord): CustomerRecord[] {
  const all = getAllCustomers();
  const upperCode = newCustomer.code.trim().toUpperCase();

  const existingIdx = all.findIndex((c) => c.code.toUpperCase() === upperCode);
  let updated: CustomerRecord[];

  if (existingIdx >= 0) {
    updated = [...all];
    updated[existingIdx] = { ...newCustomer, code: upperCode };
  } else {
    updated = [...all, { ...newCustomer, code: upperCode }];
  }

  try {
    const customOnly = updated.filter(
      (c) => !CUSTOMER_DATABASE.some((base) => base.code.toUpperCase() === c.code.toUpperCase() && base.name === c.name)
    );
    localStorage.setItem(STORAGE_KEY, JSON.stringify(customOnly));
  } catch (e) {
    console.error("Error saving customer:", e);
  }

  return updated;
}

/**
 * Bulk import customers from Google Sheets or CSV/TSV copy-paste
 */
export function importCustomers(records: CustomerRecord[]): { addedCount: number; totalCount: number } {
  if (!records || records.length === 0) {
    return { addedCount: 0, totalCount: getAllCustomers().length };
  }

  const all = getAllCustomers();
  const map = new Map<string, CustomerRecord>();
  all.forEach((c) => map.set(c.code.toUpperCase(), c));

  let added = 0;
  records.forEach((rec) => {
    if (!rec.name || !rec.name.trim()) return;
    const code = (rec.code && rec.code.trim()) ? rec.code.trim().toUpperCase() : getNextCustomerCode();
    if (!map.has(code)) {
      added++;
    }
    map.set(code, {
      code,
      name: rec.name.trim().toUpperCase(),
      address: (rec.address || "UNAI").trim(),
      phone: (rec.phone || "").trim(),
    });
  });

  const merged = Array.from(map.values());
  try {
    const customOnly = merged.filter(
      (c) => !CUSTOMER_DATABASE.some((base) => base.code.toUpperCase() === c.code.toUpperCase() && base.name === c.name)
    );
    localStorage.setItem(STORAGE_KEY, JSON.stringify(customOnly));
  } catch (e) {
    console.error("Error saving imported customers:", e);
  }

  return { addedCount: added, totalCount: merged.length };
}

/**
 * Find customer exact match by name or phone
 */
export function findCustomerExact(nameOrPhone: string): CustomerRecord | undefined {
  if (!nameOrPhone || !nameOrPhone.trim()) return undefined;
  const q = nameOrPhone.trim().toLowerCase();
  const cleanPhone = nameOrPhone.replace(/[^0-9]/g, "");
  const all = getAllCustomers();

  return all.find(
    (c) =>
      c.name.toLowerCase() === q ||
      (cleanPhone.length >= 8 && c.phone.replace(/[^0-9]/g, "") === cleanPhone) ||
      c.code.toLowerCase() === q
  );
}

/**
 * Search customer by name or phone or code across all registered customers
 */
export function searchCustomer(query: string): CustomerRecord[] {
  if (!query || query.trim().length === 0) return [];
  const q = query.toLowerCase().trim();
  const cleanDigits = q.replace(/[^0-9]/g, "");
  const all = getAllCustomers();

  return all.filter(
    (c) =>
      c.name.toLowerCase().includes(q) ||
      (cleanDigits.length > 2 && c.phone.replace(/[^0-9]/g, "").includes(cleanDigits)) ||
      c.code.toLowerCase().includes(q) ||
      (c.address && c.address.toLowerCase().includes(q))
  ).slice(0, 10);
}
